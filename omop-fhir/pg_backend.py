"""Adaptador PostgreSQL para el subconjunto educativo del laboratorio."""
import psycopg


class Record(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def record_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Record(zip(names, values))


class Database:
    def __init__(self, url, schema):
        self.transactions = []
        self.connection = psycopg.connect(url, row_factory=record_factory)
        schema = schema.replace('PRAGMA foreign_keys=ON;', '')
        schema = schema.replace('INTEGER PRIMARY KEY', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        self.connection.execute(schema)
        self.connection.commit()

    def execute(self, sql, params=()):
        return self.connection.execute(sql.replace('?', '%s'), params)

    def __enter__(self):
        transaction = self.connection.transaction()
        transaction.__enter__()
        self.transactions.append(transaction)
        return self

    def __exit__(self, *args):
        return self.transactions.pop().__exit__(*args)
